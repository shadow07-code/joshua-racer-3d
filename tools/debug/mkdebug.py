# Generate the DEBUG BUILD: _debug.html (hook.js injected before the modules) loading
# src/_debug_main.js (main.js + window.__jr3d). Both outputs are git-ignored —
# REMOVE THEM before `vercel --prod`:  python tools/debug/mkdebug.py --clean
import io, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
os.chdir(ROOT)
if "--clean" in sys.argv:
    for f in ("_debug.html", "src/_debug_main.js"):
        if os.path.exists(f):
            os.remove(f)
    print("debug build removed")
    sys.exit(0)
s = io.open("index.html", encoding="utf-8").read()
hook = io.open(os.path.join("tools", "debug", "hook.js"), encoding="utf-8").read()
i = s.index('<script type="importmap">')
s = s[:i] + "<script>\n" + hook + "\n</script>\n" + s[i:]
assert s.count('src="./src/main.js"') == 1
s = s.replace('src="./src/main.js"', 'src="./src/_debug_main.js"')
io.open("_debug.html", "w", encoding="utf-8", newline="\n").write(s)
m = io.open("src/main.js", encoding="utf-8").read()
m += """
// -- DEBUG ONLY (generated by tools/debug/mkdebug.py, git-ignored, never deployed) --
import { CAMERA as __CAM, ROAD as __ROAD } from "./config.js";
import { params as __cp } from "./comfort.js";
window.__jr3d = {
  CAMERA: __CAM, ROAD: __ROAD, THREE, cp: __cp,
  player, traffic, heat, car, chase, camera, road, particles, juice, pose, STEER, PHYS, scene, renderer, fx, effects,
  get state() { return state; }, get chain() { return chain; },
  clearTraffic(ahead = 1e6) { traffic.list.length = 0; traffic.coins.length = 0; traffic.nitros.length = 0; traffic.ramps.length = 0; traffic.nextRowZ = player.z + ahead; },
  setHeat(v) { heat.v = v; },
};
"""
io.open("src/_debug_main.js", "w", encoding="utf-8", newline="\n").write(m)
print("debug build written")
